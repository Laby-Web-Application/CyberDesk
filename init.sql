-- ==============================================================================
-- CyberDesk Database Schema
-- Used by: ALL environments (AWS RDS Postgres, Local Docker Postgres, SQLite tests)
--
-- Executed by: app.py -> init_db() (invoked via scripts/bootstrap_db.py at boot)
-- Every statement uses `IF NOT EXISTS` so it is 100% idempotent and safe to run
-- on every container startup without wiping existing data.
--
-- IMPORTANT PARSER NOTE:
--   app.py splits this file using `schema.split(';')`. Never place a semicolon
--   inside a SQL comment here, or it will break the statement splitter.
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 1. USERS TABLE (Authentication & Role-Based Access Control)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    -- Auto-incrementing unique user ID (stored in the signed Flask session cookie)
    id SERIAL PRIMARY KEY,
    -- Login name (3-50 chars, validated in app.py)
    username VARCHAR(50) UNIQUE NOT NULL,
    -- Salted cryptographic hash generated by Werkzeug (scrypt/pbkdf2), NEVER plaintext
    password TEXT NOT NULL,
    -- RBAC role enforced at the database level via CHECK constraint
    -- Even a buggy query cannot insert an invalid role
    role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Functional unique index enforcing case-insensitive uniqueness on usernames.
-- Prevents "Alice" and "alice" from registering as two separate accounts.
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (LOWER(username));

-- ------------------------------------------------------------------------------
-- 2. REPORTS TABLE (Core Vulnerability Tracker)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reports (
    id SERIAL PRIMARY KEY,
    -- Username of the report submitter (used for ownership checks / IDOR defense)
    author VARCHAR(50) NOT NULL,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    -- Database-level allowlist for severity levels (defense-in-depth alongside app.py)
    severity VARCHAR(20) NOT NULL CHECK (severity IN ('Niska','Średnia','Wysoka','Krytyczna')),
    -- Moderation flag: FALSE = hidden from public (visible only to author & admin)
    approved BOOLEAN NOT NULL DEFAULT FALSE,
    -- Database-level allowlist for workflow statuses
    status VARCHAR(30) NOT NULL DEFAULT 'Nowe' CHECK (status IN ('Nowe','W trakcie analizy','Naprawione')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Indexes to speed up the two most common WHERE filters in app.py:
--   /my-reports filters by `author`
--   / (public homepage) and /admin filter by `approved`
CREATE INDEX IF NOT EXISTS reports_author ON reports (author);
CREATE INDEX IF NOT EXISTS reports_approved ON reports (approved);

-- ------------------------------------------------------------------------------
-- 3. COMMENTS TABLE (Report Discussions)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS comments (
    id SERIAL PRIMARY KEY,
    -- Foreign key linking each comment to its parent report.
    -- ON DELETE CASCADE ensures that when an admin deletes a report, PostgreSQL
    -- (and SQLite with PRAGMA foreign_keys = ON) automatically deletes all of
    -- its comments so no orphaned rows are left behind.
    report_id INTEGER NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    author VARCHAR(50) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Speeds up loading all comments for a specific report on /reports/<id>
CREATE INDEX IF NOT EXISTS comments_report ON comments (report_id);

-- ------------------------------------------------------------------------------
-- 4. LOGIN_ATTEMPTS TABLE (Distributed Brute-Force Rate Limiting)
-- ------------------------------------------------------------------------------
-- Stored in PostgreSQL instead of in-memory Python dictionaries so rate limits
-- are shared across all Gunicorn workers and all EC2 instances behind the ALB.
CREATE TABLE IF NOT EXISTS login_attempts (
    -- SHA-256 hex digest (64 chars) of either `account:<ip>:<username>` or `ip:<ip>`
    key VARCHAR(64) PRIMARY KEY,
    -- Number of failed attempts within the current 15-minute window
    attempts INTEGER NOT NULL DEFAULT 0,
    -- Unix timestamp (seconds) of the most recent failed attempt
    last_attempt BIGINT NOT NULL,
    -- Unix timestamp (seconds) until which login is blocked (HTTP 429)
    blocked_until BIGINT NOT NULL DEFAULT 0
);

-- Speeds up periodic cleanup of expired rate-limit rows (avoids full table scans)
CREATE INDEX IF NOT EXISTS login_attempts_last_attempt ON login_attempts (last_attempt);

-- ------------------------------------------------------------------------------
-- 5. AUDIT_EVENTS TABLE (Admin Activity & Security Trail)
-- ------------------------------------------------------------------------------
-- Append-only log of key actions (report created, edited, approved, status
-- changed, deleted, comment added/deleted) shown on /admin/audit.
CREATE TABLE IF NOT EXISTS audit_events (
    id SERIAL PRIMARY KEY,
    -- Username of the person who performed the action
    actor VARCHAR(50) NOT NULL,
    -- Human-readable event label (e.g. "Zmieniono status", "Usunięto zgłoszenie")
    event VARCHAR(100) NOT NULL,
    -- Optional reference to the affected report ID (NOT a foreign key, so audit
    -- records survive even after a report is deleted)
    report_id INTEGER,
    -- Extra context (e.g. old status -> new status, or deleted report title)
    detail TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);



























